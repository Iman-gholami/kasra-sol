-- Additive: one stock for the shop floor and the website. Goods are received into the shared variant stock
-- with a printed barcode per color/size, and in-store sales scan that barcode and take from the same stock.
-- Nothing here rewrites products, variants or orders.

-- Shop-internal EAN-13 codes (prefix 20, GS1's range for numbers used only inside one store), one per
-- product/color/size. A code belongs to the product/color/size rather than to a variant row, so labels already stuck
-- on clothes keep scanning when the product editor removes and later restores that color or size.
CREATE SEQUENCE IF NOT EXISTS variant_barcode_seq START 1;
CREATE TABLE IF NOT EXISTS variant_barcodes (
  code char(13) PRIMARY KEY CHECK (code ~ '^20[0-9]{11}$'),
  product_id varchar(80) NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id varchar(80) NOT NULL,
  size varchar(20) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT variant_barcodes_variant_key UNIQUE (product_id, color_id, size)
);

-- Goods received into stock. `client_ref` is generated by the panel for each submission, so a repeated click or
-- a retried request adds the units once. Names and colors are snapshots, as in order_items.
CREATE TABLE IF NOT EXISTS stock_receipts (
  id bigserial PRIMARY KEY,
  client_ref uuid NOT NULL UNIQUE,
  note varchar(300),
  actor_id uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS stock_receipts_created_idx ON stock_receipts(created_at DESC);
CREATE TABLE IF NOT EXISTS stock_receipt_items (
  id bigserial PRIMARY KEY,
  receipt_id bigint NOT NULL REFERENCES stock_receipts(id) ON DELETE CASCADE,
  product_id varchar(80) NOT NULL,
  name text NOT NULL,
  color_id varchar(80) NOT NULL,
  color_name text,
  size varchar(20) NOT NULL,
  barcode char(13) NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS stock_receipt_items_receipt_idx ON stock_receipt_items(receipt_id);

-- Sales at the shop counter. Prices are the catalog price at the moment of sale; a voided sale returns its units.
CREATE TABLE IF NOT EXISTS store_sales (
  id bigserial PRIMARY KEY,
  client_ref uuid NOT NULL UNIQUE,
  payment varchar(20) NOT NULL CHECK (payment IN ('cash', 'card', 'transfer')),
  subtotal integer NOT NULL CHECK (subtotal >= 0),
  discount integer NOT NULL DEFAULT 0 CHECK (discount >= 0 AND discount <= subtotal),
  total integer NOT NULL,
  note varchar(300),
  actor_id uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  voided_at timestamptz,
  voided_by uuid REFERENCES admin_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT store_sales_total_check CHECK (total = subtotal - discount)
);
CREATE INDEX IF NOT EXISTS store_sales_created_idx ON store_sales(created_at DESC);
CREATE TABLE IF NOT EXISTS store_sale_items (
  id bigserial PRIMARY KEY,
  sale_id bigint NOT NULL REFERENCES store_sales(id) ON DELETE CASCADE,
  product_id varchar(80) NOT NULL,
  name text NOT NULL,
  color_id varchar(80) NOT NULL,
  color_name text,
  size varchar(20) NOT NULL,
  barcode char(13) NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price integer NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX IF NOT EXISTS store_sale_items_sale_idx ON store_sale_items(sale_id);
